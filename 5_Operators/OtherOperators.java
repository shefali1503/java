public class OtherOperators {
    // operators in programming languages are special symbols or keywords that
    // represent specific computations or actions performed on the data values
    public static void main(String[] args) {
        // types of operators on the basis of operands
        // unary operators --- that requires only one operand
        int n = 7;
        n++;
        System.out.println(n);

        // binary operators -- that requires 2 operands

        int result = 3 + 4;
        System.out.println(result);

        // ternary operator -- variable = (condition) ? value_if_true : value_if_false;
        int r = (4 > 0) ? 5 : 6;
        System.out.println(r);

        /*
         * Order of Operations
         * Here are some common operators, from highest to lowest priority:
         * 
         * () - Parentheses
         * , /, % - Multiplication, Division, Modulus
         * +, - - Addition, Subtraction
         * >, <, >=, <= - Comparison
         * ==, != - Equality
         * && - Logical AND
         * || - Logical OR
         * = - Assignment
         */

    }

}
