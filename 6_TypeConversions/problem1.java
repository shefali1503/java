
public class problem1 {

    public static void main(String[] args) {
        // int to double (smaller to greater =-- implicit)
        int a = 100;
        double d1 = a;
        System.out.println(d1);


        //float to double (smaller to greater =-- implicit)

        float ff = 5.46f;
        double d2 = ff;

        System.out.println(d2);

        // char to its ASCII value
        char ch = 'A';
        int ascii_value = ch;
        System.out.println(ascii_value);

        // ascii value to char
        char c = (char) ascii_value;

        System.out.println(c);

        // double to int
        double dd =  45.6578;
        int number = (int) dd;

    System.out.println(number);


    }

}
